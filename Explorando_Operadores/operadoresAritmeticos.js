// Operadores matemáticos em JavaScript


const primeiroNumero = 10;
const segundoNumero = 3;

console.log("Primeiro número: " + primeiroNumero);
console.log("Segundo número: " + segundoNumero);

// Operadores aritméticos
console.log("Soma: " + (primeiroNumero + segundoNumero));
console.log("Subtração: " + (primeiroNumero - segundoNumero));
console.log("Multiplicação: " + (primeiroNumero * segundoNumero));
console.log("Divisão: " + (primeiroNumero / segundoNumero));
console.log("Resto da divisão: " + (primeiroNumero % segundoNumero));
console.log("Potência: " + (primeiroNumero ** segundoNumero));

// Os parênteses deixam a ordem de cálculo explícita.
const resultado = (primeiroNumero + segundoNumero) * 2;
console.log("Resultado da expressão (10 + 3) * 2: " + resultado);

