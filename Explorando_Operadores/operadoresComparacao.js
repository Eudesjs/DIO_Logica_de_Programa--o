//Operadores de Comparação

let n1 = "2";

console.log(n1 == "2");

// (=) é Atribuição

let marca = "Apple";

// ( == ) é comparar o valor

console.log(marca == "Apple");

// ( === ) é para comparar o valor e o formato do conteudo.

console.log(marca === "Apple");

// ( !== ) é diferente  

console.log(marca !== "Samsung");